def pushnum(k, c):
    """Lean ` pushNum k c = pushTerm k ( encodeNatΓ' c ) ` : comma, then the bits from the last one"""
    bits = []
    n = c
    while n > 0:
        bits.append(n % 2); n //= 2
    return seq(*([push(k, '4')] + [push(k, BIT1_ if b else BIT0_) for b in reversed(bits)])) if bits else push(k, '4')


def forentries(x, body):
    """Lean ` forEntries x body = peekBra x ; loop ( !flag ) ( body ; peekBra x ) ` """
    return seq(peekbra(x), loop(CNFL, seq(body, peekbra(x))))


class _C:
    """two passes: names in program order (own labels Z1 Z2 ..., callee entries Y1 Y2 ...), then the
    equations with their continuations"""
    def __init__(self):
        self.labels, self.eqs, self.children, self.n, self.m = [], [], [], 0, 0
        self.ent = {}
        self.cslot = {}

    def name(self, t):
        """phase 1: the entry name of every node, in program order"""
        op = t[0]
        if op == 'seq':
            for x in t[1:]:
                self.name(x)
            self.ent[id(t)] = self.ent[id(t[1])]
            return
        if op == 'call':
            self.m += 1
            en = 'Y%d' % self.m
            self.ent[id(t)] = en
            self.cslot[id(t)] = len(self.children)
            self.children.append(None)
            return
        self.n += 1
        L = 'Z%d' % self.n
        self.ent[id(t)] = L
        self.labels.append(L)
        if op == 'ite':
            self.name(t[2]); self.name(t[3])
        elif op == 'loop':
            self.name(t[2])

    def go(self, t, k):
        """phase 2: compile t with continuation label k; return the entry name"""
        op = t[0]
        if op == 'seq':
            e = k
            for x in reversed(t[1:]):
                e = self.go(x, e)
            return e
        if op == 'call':
            en = self.ent[id(t)]
            self.children[self.cslot[id(t)]] = (t[1], t[2], en, k)
            return en
        L = self.ent[id(t)]
        if op == 'push':
            st = PUSH(t[1], CONST(t[2]), GT(k))
        elif op == 'pushf':
            st = PUSH(t[1], t[2], GT(k))
        elif op == 'peek':
            st = PEEK(t[1], t[2], GT(k))
        elif op == 'pop':
            st = POP(t[1], t[2], GT(k))
        elif op == 'load':
            st = LOAD(t[1], GT(k))
        elif op == 'skip':
            st = LOAD(LID, GT(k))
        elif op == 'ite':
            a = self.go(t[2], k)
            b = self.go(t[3], k)
            st = BRANCH(t[1], GT(a), GT(b))
        elif op == 'loop':
            b = self.go(t[2], L)
            st = BRANCH(t[1], GT(b), GT(k))
        else:
            raise ValueError(op)
        self.eqs.append((L, MEQ(L, st)))
        return L


def frag(name, const, ks, prog, lean):
    """register the installation predicate of the fragment ` prog ` (a node tree over the letters ks)"""
    c = _C()
    c.name(prog)
    entry = c.go(prog, 'E')
    labels = list(c.labels)
    start = None
    if entry in labels:
        labels.remove(entry)
        labels = [entry] + labels
    else:
        start = entry
    byl = dict(c.eqs)
    progt = grp([byl[l] for l in labels]) if labels else None
    labt = grp([LAB(l) for l in labels] + [LAB('E')]) if labels else None
    f = comp(name, const, ks, labels, 'E', progt, labt, lean, c.children)
    if start is not None:
        f.start = start
    return f


