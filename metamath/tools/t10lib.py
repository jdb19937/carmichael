# ------------------------------------------------------------ the fragment compiler
# nodes: ('call', fname, ks) | ('push', k, sym) | ('pushf', k, fn) | ('peek', k, h) | ('pop', k, h)
#        | ('load', f) | ('skip',) | ('seq', a, b, ...) | ('ite', c, F, G) | ('loop', c, B)
def call(f, ks): return ('call', f, list(ks))
def seq(*xs): return ('seq',) + tuple(xs)
def ite(c, a, b): return ('ite', c, a, b)
def loop(c, b): return ('loop', c, b)
def push(k, z): return ('push', k, z)
def load(f): return ('load', f)
SKIP = ('skip',)
def peekbra(k): return ('peek', k, 'TMrdBra')
