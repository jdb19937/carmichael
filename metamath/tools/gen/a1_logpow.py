"""Sortie A1, batch 6: the eventual bound ( log u ) ^ 2 <_ u ^c E (LogPow.lean)."""
import sys, os; sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..')); import a1lib; from tm import *
only = sys.argv[1:]
def run(w):
    if only and w.label not in only: return True
    return w.run()

BODY = lambda X: '( ( ( log ` %s ) ^c 2 ) / ( %s ^c E ) )' % (X, X)
F = '( n e. RR+ |-> %s )' % BODY('n')
PH = 'E e. RR+'
HYU = lambda X: '( y <_ %s -> ( abs ` ( %s - 0 ) ) < 1 )' % (X, BODY(X))
HY = 'A. n e. RR+ %s' % HYU('n')
EX = 'E. y e. RR %s' % HY
M = '( ( abs ` y ) + 2 )'
BND = lambda X: '( ( log ` %s ) ^ 2 ) <_ ( %s ^c E )' % (X, X)
RAL = lambda MM: 'A. u e. ( %s [,) +oo ) %s' % (MM, BND('u'))
GOAL = 'E. m e. RR %s' % RAL('m')

w = W('logsqlerpow', 'The square of the logarithm is eventually dominated by any positive power (Lean: eventually_log_sq_le_rpow in LogPow.lean): for every E e. RR+ there is a threshold beyond which ( log u ) ^ 2 <_ ( u ^c E ).')
e0 = w.s([], 'id', '( %s -> %s )' % (PH, PH))
er = w.s([e0], 'rpred', '( %s -> E e. RR )' % PH)
c2 = w.s([w.s([], '2cn', '2 e. CC')], 'a1i', '( %s -> 2 e. CC )' % PH)
lim = w.s([c2, e0, w.inst('cxploglim2')], 'syl2anc', '( %s -> %s ~~>r 0 )' % (PH, F))

# the body is a complex number for every n e. RR+
C1 = '( %s /\\ n e. RR+ )' % PH
nrp = w.s([], 'simpr', '( %s -> n e. RR+ )' % C1)
erd = w.s([er], 'adantr', '( %s -> E e. RR )' % C1)
lgr = w.s([nrp, w.inst('relogcl')], 'syl', '( %s -> ( log ` n ) e. RR )' % C1)
lgc = w.s([lgr], 'recnd', '( %s -> ( log ` n ) e. CC )' % C1)
c2b = w.s([w.s([], '2cn', '2 e. CC')], 'a1i', '( %s -> 2 e. CC )' % C1)
sqc = w.s([lgc, c2b, w.inst('cxpcl')], 'syl2anc', '( %s -> ( ( log ` n ) ^c 2 ) e. CC )' % C1)
uec = w.s([nrp, erd], 'rpcxpcld', '( %s -> ( n ^c E ) e. RR+ )' % C1)
uecn = w.s([uec], 'rpcnd', '( %s -> ( n ^c E ) e. CC )' % C1)
uen0 = w.s([uec], 'rpne0d', '( %s -> ( n ^c E ) =/= 0 )' % C1)
bodycc = w.s([sqc, uecn, uen0], 'divcld', '( %s -> %s e. CC )' % (C1, BODY('n')))
ral1 = w.s([bodycc], 'ralrimiva', '( %s -> A. n e. RR+ %s e. CC )' % (PH, BODY('n')))
r1 = w.s([w.s([], '1rp', '1 e. RR+')], 'a1i', '( %s -> 1 e. RR+ )' % PH)
rl = w.s([ral1, r1, lim], 'rlimi', '( %s -> %s )' % (PH, EX))

# from a threshold y to the threshold ( abs ` y ) + 2
P2 = '( ( %s /\\ y e. RR ) /\\ %s )' % (PH, HY)
eph = w.s([], 'simpll', '( %s -> %s )' % (P2, PH))
yr = w.s([], 'simplr', '( %s -> y e. RR )' % P2)
hy = w.s([], 'simpr', '( %s -> %s )' % (P2, HY))
ycn = w.s([yr], 'recnd', '( %s -> y e. CC )' % P2)
ay = w.s([ycn], 'abscld', '( %s -> ( abs ` y ) e. RR )' % P2)
ay0 = w.s([ycn], 'absge0d', '( %s -> 0 <_ ( abs ` y ) )' % P2)
yle = w.s([yr], 'leabsd', '( %s -> y <_ ( abs ` y ) )' % P2)
r2 = w.s([w.s([], '2re', '2 e. RR')], 'a1i', '( %s -> 2 e. RR )' % P2)
mr = w.s([ay, r2], 'readdcld', '( %s -> %s e. RR )' % (P2, M))
le02 = w.s([w.s([], '0le2', '0 <_ 2')], 'a1i', '( %s -> 0 <_ 2 )' % P2)
bi1 = w.s([ay, r2, w.inst('addge01')], 'syl2anc', '( %s -> ( 0 <_ 2 <-> ( abs ` y ) <_ %s ) )' % (P2, M))
am = w.s([le02, bi1], 'mpbid', '( %s -> ( abs ` y ) <_ %s )' % (P2, M))
bi2 = w.s([ay, r2, w.inst('addge02')], 'syl2anc', '( %s -> ( 0 <_ ( abs ` y ) <-> 2 <_ %s ) )' % (P2, M))
tm = w.s([ay0, bi2], 'mpbid', '( %s -> 2 <_ %s )' % (P2, M))

# the bound for one u above the threshold
P3 = '( %s /\\ u e. ( %s [,) +oo ) )' % (P2, M)
uel = w.s([], 'simpr', '( %s -> u e. ( %s [,) +oo ) )' % (P3, M))
mr3 = w.s([mr], 'adantr', '( %s -> %s e. RR )' % (P3, M))
ic = w.s([mr3, w.inst('elicopnf')], 'syl', '( %s -> ( u e. ( %s [,) +oo ) <-> ( u e. RR /\\ %s <_ u ) ) )' % (P3, M, M))
ui = w.s([uel, ic], 'mpbid', '( %s -> ( u e. RR /\\ %s <_ u ) )' % (P3, M))
ur = w.s([ui], 'simpld', '( %s -> u e. RR )' % P3)
mle = w.s([ui], 'simprd', '( %s -> %s <_ u )' % (P3, M))
yr3 = w.s([yr], 'adantr', '( %s -> y e. RR )' % P3)
ay3 = w.s([ay], 'adantr', '( %s -> ( abs ` y ) e. RR )' % P3)
am3 = w.s([am], 'adantr', '( %s -> ( abs ` y ) <_ %s )' % (P3, M))
yle3 = w.s([yle], 'adantr', '( %s -> y <_ ( abs ` y ) )' % P3)
tm3 = w.s([tm], 'adantr', '( %s -> 2 <_ %s )' % (P3, M))
r23 = w.s([w.s([], '2re', '2 e. RR')], 'a1i', '( %s -> 2 e. RR )' % P3)
z3 = w.s([], '0red', '( %s -> 0 e. RR )' % P3)
o3 = w.s([], '1red', '( %s -> 1 e. RR )' % P3)
aylu = w.s([ay3, mr3, ur, am3, mle], 'letrd', '( %s -> ( abs ` y ) <_ u )' % P3)
ylu = w.s([yr3, ay3, ur, yle3, aylu], 'letrd', '( %s -> y <_ u )' % P3)
tu = w.s([r23, mr3, ur, tm3, mle], 'letrd', '( %s -> 2 <_ u )' % P3)
p2pos = w.s([w.s([], '2pos', '0 < 2')], 'a1i', '( %s -> 0 < 2 )' % P3)
u0 = w.s([z3, r23, ur, p2pos, tu], 'ltletrd', '( %s -> 0 < u )' % P3)
urp = w.s([ur, u0], 'elrpd', '( %s -> u e. RR+ )' % P3)
lt12 = w.s([w.s([], '1lt2', '1 < 2')], 'a1i', '( %s -> 1 < 2 )' % P3)
u1 = w.s([o3, r23, ur, lt12, tu], 'ltletrd', '( %s -> 1 < u )' % P3)
lgrp = w.s([ur, u1, w.inst('rplogcl')], 'syl2anc', '( %s -> ( log ` u ) e. RR+ )' % P3)
lgre = w.s([lgrp], 'rpred', '( %s -> ( log ` u ) e. RR )' % P3)
lgcn = w.s([lgrp], 'rpcnd', '( %s -> ( log ` u ) e. CC )' % P3)
lgn0 = w.s([lgrp], 'rpne0d', '( %s -> ( log ` u ) =/= 0 )' % P3)
z2 = w.s([w.s([], '2z', '2 e. ZZ')], 'a1i', '( %s -> 2 e. ZZ )' % P3)
cxe = w.s([lgcn, lgn0, z2], 'cxpexpzd', '( %s -> ( ( log ` u ) ^c 2 ) = ( ( log ` u ) ^ 2 ) )' % P3)
beq = w.s([cxe], 'oveq1d', '( %s -> %s = ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) )' % (P3, BODY('u')))
er2 = w.s([eph], 'rpred', '( %s -> E e. RR )' % P2)
er3 = w.s([er2], 'adantr', '( %s -> E e. RR )' % P3)
uerp = w.s([urp, er3], 'rpcxpcld', '( %s -> ( u ^c E ) e. RR+ )' % P3)
sqre = w.s([lgre], 'resqcld', '( %s -> ( ( log ` u ) ^ 2 ) e. RR )' % P3)
sq0 = w.s([lgre], 'sqge0d', '( %s -> 0 <_ ( ( log ` u ) ^ 2 ) )' % P3)
qre = w.s([sqre, uerp], 'rerpdivcld', '( %s -> ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) e. RR )' % P3)
q0 = w.s([sqre, uerp, sq0], 'divge0d', '( %s -> 0 <_ ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) )' % P3)
qcn = w.s([qre], 'recnd', '( %s -> ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) e. CC )' % P3)
bcn = w.s([beq, qcn], 'eqeltrd', '( %s -> %s e. CC )' % (P3, BODY('u')))
hy3 = w.s([hy], 'adantr', '( %s -> %s )' % (P3, HY))
idn = w.s([], 'id', '( n = u -> n = u )')
cgw, bw = w.wcongr(HYU('n'), {'n': 'u'}, 'n = u', {'n': idn}); assert bw == HYU('u'), bw
inst = w.s([cgw, hy3, urp], 'rspcdva', '( %s -> %s )' % (P3, HYU('u')))
lt1 = w.s([ylu, inst], 'mpd', '( %s -> ( abs ` ( %s - 0 ) ) < 1 )' % (P3, BODY('u')))
sid = w.s([bcn, w.inst('subid1')], 'syl', '( %s -> ( %s - 0 ) = %s )' % (P3, BODY('u'), BODY('u')))
sid2 = w.s([sid], 'fveq2d', '( %s -> ( abs ` ( %s - 0 ) ) = ( abs ` %s ) )' % (P3, BODY('u'), BODY('u')))
sid3 = w.s([beq], 'fveq2d', '( %s -> ( abs ` %s ) = ( abs ` ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) ) )' % (P3, BODY('u')))
sid4 = w.s([sid2, sid3], 'eqtrd', '( %s -> ( abs ` ( %s - 0 ) ) = ( abs ` ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) ) )' % (P3, BODY('u')))
aid = w.s([qre, q0], 'absidd', '( %s -> ( abs ` ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) ) = ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) )' % P3)
sid5 = w.s([sid4, aid], 'eqtrd', '( %s -> ( abs ` ( %s - 0 ) ) = ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) )' % (P3, BODY('u')))
qlt = w.s([sid5, lt1], 'eqbrtrrd', '( %s -> ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) < 1 )' % P3)
dl = w.s([sqre, uerp, w.inst('divlt1lt')], 'syl2anc', '( %s -> ( ( ( ( log ` u ) ^ 2 ) / ( u ^c E ) ) < 1 <-> ( ( log ` u ) ^ 2 ) < ( u ^c E ) ) )' % P3)
slt = w.s([qlt, dl], 'mpbid', '( %s -> ( ( log ` u ) ^ 2 ) < ( u ^c E ) )' % P3)
uere = w.s([uerp], 'rpred', '( %s -> ( u ^c E ) e. RR )' % P3)
sle = w.s([sqre, uere, slt], 'ltled', '( %s -> %s )' % (P3, BND('u')))
ralu = w.s([sle], 'ralrimiva', '( %s -> %s )' % (P2, RAL(M)))
P4 = '( %s /\\ m = %s )' % (P2, M)
idm = w.s([], 'simpr', '( %s -> m = %s )' % (P4, M))
cgm, bm = w.wcongr(RAL('m'), {'m': M}, P4, {'m': idm}); assert bm == RAL(M), bm
ex1 = w.s([mr, cgm, ralu], 'rspcedvd', '( %s -> %s )' % (P2, GOAL))
exd = w.s([ex1], 'ex', '( ( %s /\\ y e. RR ) -> ( %s -> %s ) )' % (PH, HY, GOAL))
rlim = w.s([exd], 'rexlimdva', '( %s -> ( %s -> %s ) )' % (PH, EX, GOAL))
w.qed([rl, rlim], 'mpd', '( %s -> %s )' % (PH, GOAL))
run(w)
