def hashcnt(w, ante, fin_step, setexpr):
    """( ante -> ( # ` set ) e. RR ) and ( ante -> 0 <_ ( # ` set ) ) from fin_step : ( ante -> set e. Fin )"""
    n0 = w.s([fin_step, w.inst('hashcl')], 'syl', '( %s -> ( # ` %s ) e. NN0 )' % (ante, setexpr))
    return w.s([n0], 'nn0red', '( %s -> ( # ` %s ) e. RR )' % (ante, setexpr)), w.s([n0], 'nn0ge0d', '( %s -> 0 <_ ( # ` %s ) )' % (ante, setexpr))


def gen_dc():
    w = W('bmdc', 'The double counting of the pairs ` ( d , k ) ` with ` d k + 1 ` a prime up to ` M ` and the pigeonhole over the shifts ` k ` (Lean ` hcount ` , ` hsum_lb ` , ` hex ` in ` pigeonhole_of_BMembership ` ): if every ` d e. D ` has at least ` C ` good shifts in ` K ` and ` # K <_ X ` , some ` k e. K ` is good for at least ` C # D / X ` divisors (~ bmhashsum , ~ fsumcom , ~ fsumlt ).')
    PK = lambda o: '{ k e. K | %s }' % PCOND(o, 'k', 'M')
    PD = lambda u: '{ v e. D | %s }' % PCOND('v', u, 'M')
    HYP = 'A. o e. D C <_ ( # ` %s )' % PK('o')
    A = '( ( D e. Fin /\\ K e. Fin /\\ K =/= (/) ) /\\ ( ( X e. RR /\\ 0 < X ) /\\ ( C e. RR /\\ 0 <_ C ) /\\ ( # ` K ) <_ X ) /\\ %s )' % HYP
    CP = '( ( C x. ( # ` D ) ) / X )'
    GOAL = 'E. u e. K %s <_ ( # ` %s )' % (CP, PD('u'))
    NEG = 'A. u e. K -. %s <_ ( # ` %s )' % (CP, PD('u'))
    CX = '( %s /\\ %s )' % (A, NEG)
    s = S_(w, CX)
    u = unpack(w, A)
    L = lambda x_: lift(w, x_, CX)
    dfin, kfin, kne = L(u['D e. Fin']), L(u['K e. Fin']), L(u['K =/= (/)'])
    xr, x0, cr, c0, kle, hyp = L(u['X e. RR']), L(u['0 < X']), L(u['C e. RR']), L(u['0 <_ C']), L(u['( # ` K ) <_ X']), L(u[HYP])
    neg = s([], 'simpr', NEG)
    hdr, hdg = hashcnt(w, CX, dfin, 'D'); hkr, hkg = hashcnt(w, CX, kfin, 'K')
    xrp = s([xr, x0], 'elrpd', 'X e. RR+')
    cpr = s([s([cr, hdr], 'remulcld', '( C x. ( # ` D ) ) e. RR'), xrp], 'rerpdivcld', '%s e. RR' % CP)
    cpg = s([s([cr, hdr, c0, hdg], 'mulge0d', '0 <_ ( C x. ( # ` D ) )'), xrp], 'divge0d', '0 <_ %s' % CP)
    I = lambda h, i: 'if ( %s , 1 , 0 )' % PCOND(h, i, 'M')
    # ---- for i e. K : # PD ( i ) < CP and # PD ( i ) = sum_ h e. D I ( h , i )
    CI = '( %s /\\ i e. K )' % CX
    si = S_(w, CI)
    iin = si([], 'simpr', 'i e. K')
    cg1, negi = wc(w, '-. %s <_ ( # ` %s )' % (CP, PD('u')), 'u', 'i')
    assert negi == '-. %s <_ ( # ` %s )' % (CP, PD('i')), negi
