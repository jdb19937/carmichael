"""Sortie C0b, batch 1: degenerate segments, parametrised interval points,
points of a rectangle, sub-rectangles (lintid, crectlin, crectpt, crectss2)."""
import sys, os; sys.path.insert(0, os.path.dirname(__file__)); from c0b_lib import *

# ---- lintid: the integral along a degenerate segment is zero
w = W('lintid', 'The line integral along a degenerate segment vanishes.')
A0 = '( A e. CC /\\ ( F e. ( D -cn-> CC ) /\\ ( A cseg A ) C_ D ) )'
A1x = '( %s /\\ t e. ( 0 (,) 1 ) )' % A0
ac = w.s([], 'simpl', '( %s -> A e. CC )' % A0)
fc = w.s([], 'simprl', '( %s -> F e. ( D -cn-> CC ) )' % A0)
sg = w.s([], 'simprr', '( %s -> ( A cseg A ) C_ D )' % A0)
fex = w.s([fc, w.inst('elex')], 'syl', '( %s -> F e. _V )' % A0)
INTG0 = '( ( F ` ( A + ( t x. ( A - A ) ) ) ) x. ( A - A ) )'
lv = w.s([fex, ac, ac, w.inst('lintval')], 'syl3anc',
         '( %s -> ( F lint <. A , A >. ) = S. ( 0 (,) 1 ) %s _d t )' % (A0, INTG0))
# the integrand vanishes on ( 0 (,) 1 )
t01 = w.s([], 'simpr', '( %s -> t e. ( 0 (,) 1 ) )' % A1x)
ssi = closed(w, A1x, 'ioossicc', '( 0 (,) 1 ) C_ ( 0 [,] 1 )')
ticc = w.s([ssi, t01], 'sseldd', '( %s -> t e. ( 0 [,] 1 ) )' % A1x)
ac2 = w.s([ac], 'adantr', '( %s -> A e. CC )' % A1x)
sg2 = w.s([sg], 'adantr', '( %s -> ( A cseg A ) C_ D )' % A1x)
fc2 = w.s([fc], 'adantr', '( %s -> F e. ( D -cn-> CC ) )' % A1x)
lin = w.s([ac2, ac2, ticc, w.inst('cseglin')], 'syl3anc',
          '( %s -> ( A + ( t x. ( A - A ) ) ) e. ( A cseg A ) )' % A1x)
lind = w.s([sg2, lin], 'sseldd', '( %s -> ( A + ( t x. ( A - A ) ) ) e. D )' % A1x)
ff = w.s([fc2, w.inst('cncff')], 'syl', '( %s -> F : D --> CC )' % A1x)
fv = w.s([ff, lind], 'ffvelcdmd', '( %s -> ( F ` ( A + ( t x. ( A - A ) ) ) ) e. CC )' % A1x)
s0 = w.s([ac2], 'subidd', '( %s -> ( A - A ) = 0 )' % A1x)
oe = w.s([s0], 'oveq2d', '( %s -> %s = ( ( F ` ( A + ( t x. ( A - A ) ) ) ) x. 0 ) )' % (A1x, INTG0))
m0 = w.s([fv], 'mul01d', '( %s -> ( ( F ` ( A + ( t x. ( A - A ) ) ) ) x. 0 ) = 0 )' % A1x)
eq = w.s([oe, m0], 'eqtrd', '( %s -> %s = 0 )' % (A1x, INTG0))
it = w.s([eq], 'itgeq2dv', '( %s -> S. ( 0 (,) 1 ) %s _d t = S. ( 0 (,) 1 ) 0 _d t )' % (A0, INTG0))
z = closed(w, A0, 'itgz', 'S. ( 0 (,) 1 ) 0 _d t = 0')
t2 = w.s([it, z], 'eqtrd', '( %s -> S. ( 0 (,) 1 ) %s _d t = 0 )' % (A0, INTG0))
w.qed([lv, t2], 'eqtrd', '( %s -> ( F lint <. A , A >. ) = 0 )' % A0); run(w)

# ---- crectlin: a parametrised point of a closed real interval
w = W('crectlin', 'A convex combination of the endpoints lies in the closed interval.')
A0 = '( ( M e. RR /\\ N e. RR /\\ M <_ N ) /\\ S e. ( 0 [,] 1 ) )'
mr = w.s([], 'simpl1', '( %s -> M e. RR )' % A0)
nr = w.s([], 'simpl2', '( %s -> N e. RR )' % A0)
le = w.s([], 'simpl3', '( %s -> M <_ N )' % A0)
s01 = w.s([], 'simpr', '( %s -> S e. ( 0 [,] 1 ) )' % A0)
mc = w.s([mr], 'recnd', '( %s -> M e. CC )' % A0)
nc = w.s([nr], 'recnd', '( %s -> N e. CC )' % A0)
sc = w.s([s01, w.inst('elunitcn')], 'syl', '( %s -> S e. CC )' % A0)
cv = w.s([mc, nc, sc, w.inst('cvxid')], 'syl3anc',
         '( %s -> %s = ( ( ( 1 - S ) x. M ) + ( S x. N ) ) )' % (A0, PAR('M', 'N', 'S')))
mx = w.s([mr, w.inst('rexr')], 'syl', '( %s -> M e. RR* )' % A0)
nx = w.s([nr, w.inst('rexr')], 'syl', '( %s -> N e. RR* )' % A0)
mi = w.s([mx, nx, le, w.inst('lbicc2')], 'syl3anc', '( %s -> M e. ( M [,] N ) )' % A0)
ni = w.s([mx, nx, le, w.inst('ubicc2')], 'syl3anc', '( %s -> N e. ( M [,] N ) )' % A0)
tri = w.s([mi, ni, s01], 'jca31', '( %s -> ( ( M e. ( M [,] N ) /\\ N e. ( M [,] N ) ) /\\ S e. ( 0 [,] 1 ) ) )' % A0)
tri3 = w.s([mi, ni, s01], '3jca', '( %s -> ( M e. ( M [,] N ) /\\ N e. ( M [,] N ) /\\ S e. ( 0 [,] 1 ) ) )' % A0)
ic = w.s([mr, nr, w.inst('icccvx')], 'syl2anc',
         '( %s -> ( ( M e. ( M [,] N ) /\\ N e. ( M [,] N ) /\\ S e. ( 0 [,] 1 ) ) -> ( ( ( 1 - S ) x. M ) + ( S x. N ) ) e. ( M [,] N ) ) )' % A0)
mp = w.s([tri3, ic], 'mpd', '( %s -> ( ( ( 1 - S ) x. M ) + ( S x. N ) ) e. ( M [,] N ) )' % A0)
w.qed([cv, mp], 'eqeltrd', '( %s -> %s e. ( M [,] N ) )' % (A0, PAR('M', 'N', 'S'))); run(w)

# ---- crectpt: a point with coordinates in the two intervals is in the rectangle
w = W('crectpt', 'A complex number whose real and imaginary parts lie in the two coordinate intervals is in the rectangle.')
A0 = '( %s /\\ ( X e. %s /\\ Y e. %s ) )' % (AB, RI('A', 'B'), II('A', 'B'))
ab = w.s([], 'simpl', '( %s -> %s )' % (A0, AB))
ac = w.s([], 'simpll', '( %s -> A e. CC )' % A0)
bc = w.s([], 'simplr', '( %s -> B e. CC )' % A0)
xi = w.s([], 'simprl', '( %s -> X e. %s )' % (A0, RI('A', 'B')))
yi = w.s([], 'simprr', '( %s -> Y e. %s )' % (A0, II('A', 'B')))
ar = w.s([ac, w.inst('recl')], 'syl', '( %s -> ( Re ` A ) e. RR )' % A0)
br = w.s([bc, w.inst('recl')], 'syl', '( %s -> ( Re ` B ) e. RR )' % A0)
ai = w.s([ac, w.inst('imcl')], 'syl', '( %s -> ( Im ` A ) e. RR )' % A0)
bi = w.s([bc, w.inst('imcl')], 'syl', '( %s -> ( Im ` B ) e. RR )' % A0)
ssr = w.s([ar, br, w.inst('iccssre')], 'syl2anc', '( %s -> %s C_ RR )' % (A0, RI('A', 'B')))
ssi = w.s([ai, bi, w.inst('iccssre')], 'syl2anc', '( %s -> %s C_ RR )' % (A0, II('A', 'B')))
xr = w.s([ssr, xi], 'sseldd', '( %s -> X e. RR )' % A0)
yr = w.s([ssi, yi], 'sseldd', '( %s -> Y e. RR )' % A0)
Z = PT('X', 'Y')
ic = closed(w, A0, 'ax-icn', '_i e. CC')
xc = w.s([xr], 'recnd', '( %s -> X e. CC )' % A0)
yc = w.s([yr], 'recnd', '( %s -> Y e. CC )' % A0)
iy = w.s([ic, yc], 'mulcld', '( %s -> ( _i x. Y ) e. CC )' % A0)
zc = w.s([xc, iy], 'addcld', '( %s -> %s e. CC )' % (A0, Z))
re = w.s([xr, yr, w.inst('crre')], 'syl2anc', '( %s -> ( Re ` %s ) = X )' % (A0, Z))
im = w.s([xr, yr, w.inst('crim')], 'syl2anc', '( %s -> ( Im ` %s ) = Y )' % (A0, Z))
rem = w.s([re, xi], 'eqeltrd', '( %s -> ( Re ` %s ) e. %s )' % (A0, Z, RI('A', 'B')))
imm = w.s([im, yi], 'eqeltrd', '( %s -> ( Im ` %s ) e. %s )' % (A0, Z, II('A', 'B')))
tri = w.s([zc, rem, imm], '3jca', '( %s -> ( %s e. CC /\\ ( Re ` %s ) e. %s /\\ ( Im ` %s ) e. %s ) )' % (A0, Z, Z, RI('A', 'B'), Z, II('A', 'B')))
el = w.s([ab, w.inst('elcrect')], 'syl', '( %s -> ( %s e. ( A crect B ) <-> ( %s e. CC /\\ ( Re ` %s ) e. %s /\\ ( Im ` %s ) e. %s ) ) )' % (A0, Z, Z, Z, RI('A', 'B'), Z, II('A', 'B')))
w.qed([el, tri], 'mpbird', '( %s -> %s e. ( A crect B ) )' % (A0, Z)); run(w)

# ---- crectss2: a rectangle inside a rectangle
w = W('crectss2', 'A rectangle whose coordinate intervals are contained in those of another is contained in it.')
AB2 = '( C e. CC /\\ E e. CC )'
INC = '( ( ( Re ` A ) <_ ( Re ` C ) /\\ ( Re ` E ) <_ ( Re ` B ) ) /\\ ( ( Im ` A ) <_ ( Im ` C ) /\\ ( Im ` E ) <_ ( Im ` B ) ) )'
A0 = '( %s /\\ %s /\\ %s )' % (AB, AB2, INC)
A0z = '( %s /\\ z e. ( C crect E ) )' % A0
ab = w.s([], 'simp1', '( %s -> %s )' % (A0, AB))
ce = w.s([], 'simp2', '( %s -> %s )' % (A0, AB2))
ac = w.s([ab, w.inst('simpl')], 'syl', '( %s -> A e. CC )' % A0)
bc = w.s([ab, w.inst('simpr')], 'syl', '( %s -> B e. CC )' % A0)
ar = w.s([ac, w.inst('recl')], 'syl', '( %s -> ( Re ` A ) e. RR )' % A0)
br = w.s([bc, w.inst('recl')], 'syl', '( %s -> ( Re ` B ) e. RR )' % A0)
ai = w.s([ac, w.inst('imcl')], 'syl', '( %s -> ( Im ` A ) e. RR )' % A0)
bi = w.s([bc, w.inst('imcl')], 'syl', '( %s -> ( Im ` B ) e. RR )' % A0)
i1 = w.s([], 'simp3l', '( %s -> ( ( Re ` A ) <_ ( Re ` C ) /\\ ( Re ` E ) <_ ( Re ` B ) ) )' % A0)
i2 = w.s([], 'simp3r', '( %s -> ( ( Im ` A ) <_ ( Im ` C ) /\\ ( Im ` E ) <_ ( Im ` B ) ) )' % A0)
p1 = w.s([ar, br], 'jca', '( %s -> ( ( Re ` A ) e. RR /\\ ( Re ` B ) e. RR ) )' % A0)
p2 = w.s([ai, bi], 'jca', '( %s -> ( ( Im ` A ) e. RR /\\ ( Im ` B ) e. RR ) )' % A0)
sr = w.s([p1, i1, w.inst('iccss')], 'syl2anc', '( %s -> %s C_ %s )' % (A0, RI('C', 'E'), RI('A', 'B')))
si = w.s([p2, i2, w.inst('iccss')], 'syl2anc', '( %s -> %s C_ %s )' % (A0, II('C', 'E'), II('A', 'B')))
elz = w.s([ce, w.inst('elcrect')], 'syl', '( %s -> ( z e. ( C crect E ) <-> ( z e. CC /\\ ( Re ` z ) e. %s /\\ ( Im ` z ) e. %s ) ) )' % (A0, RI('C', 'E'), II('C', 'E')))
elzr = w.s([elz], 'biimpa', '( %s -> ( z e. CC /\\ ( Re ` z ) e. %s /\\ ( Im ` z ) e. %s ) )' % (A0z, RI('C', 'E'), II('C', 'E')))
zc = w.s([elzr, w.inst('simp1')], 'syl', '( %s -> z e. CC )' % A0z)
zr = w.s([elzr, w.inst('simp2')], 'syl', '( %s -> ( Re ` z ) e. %s )' % (A0z, RI('C', 'E')))
zi = w.s([elzr, w.inst('simp3')], 'syl', '( %s -> ( Im ` z ) e. %s )' % (A0z, II('C', 'E')))
sr2 = w.s([sr], 'adantr', '( %s -> %s C_ %s )' % (A0z, RI('C', 'E'), RI('A', 'B')))
si2 = w.s([si], 'adantr', '( %s -> %s C_ %s )' % (A0z, II('C', 'E'), II('A', 'B')))
zr2 = w.s([sr2, zr], 'sseldd', '( %s -> ( Re ` z ) e. %s )' % (A0z, RI('A', 'B')))
zi2 = w.s([si2, zi], 'sseldd', '( %s -> ( Im ` z ) e. %s )' % (A0z, II('A', 'B')))
tri = w.s([zc, zr2, zi2], '3jca', '( %s -> ( z e. CC /\\ ( Re ` z ) e. %s /\\ ( Im ` z ) e. %s ) )' % (A0z, RI('A', 'B'), II('A', 'B')))
ab2 = w.s([ab], 'adantr', '( %s -> %s )' % (A0z, AB))
elw = w.s([ab2, w.inst('elcrect')], 'syl', '( %s -> ( z e. ( A crect B ) <-> ( z e. CC /\\ ( Re ` z ) e. %s /\\ ( Im ` z ) e. %s ) ) )' % (A0z, RI('A', 'B'), II('A', 'B')))
mm = w.s([elw, tri], 'mpbird', '( %s -> z e. ( A crect B ) )' % A0z)
ex = w.s([mm], 'ex', '( %s -> ( z e. ( C crect E ) -> z e. ( A crect B ) ) )' % A0)
w.qed([ex], 'ssrdv', '( %s -> ( C crect E ) C_ ( A crect B ) )' % A0); run(w)
