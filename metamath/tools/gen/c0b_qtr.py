"""Sortie C0b, batch 3: the midpoint identity, the unit-interval fact for 1/2,
and the quartering identity rectintqtr."""
import sys, os; sys.path.insert(0, os.path.dirname(__file__)); from c0b_lib import *

RA = RE('A'); RB = RE('B'); IA = IM('A'); IB = IM('B')
HALF = '( 1 / 2 )'

# ---- halfunit
w = W('halfunit', 'One half lies in the closed unit interval.')
r0 = w.s([], '0re', '0 e. RR'); r1 = w.s([], '1re', '1 e. RR')
hr = w.s([], 'halfre', '( 1 / 2 ) e. RR')
hg = w.s([], 'halfge0', '0 <_ ( 1 / 2 )')
hlt = w.s([], 'halflt1', '( 1 / 2 ) < 1')
hle = w.s([hr, r1, hlt], 'ltleii', '( 1 / 2 ) <_ 1')
tri = w.s([hr, hg, hle], '3pm3.2i', '( ( 1 / 2 ) e. RR /\\ 0 <_ ( 1 / 2 ) /\\ ( 1 / 2 ) <_ 1 )')
e = w.s([r0, r1, w.inst('elicc2')], 'mp2an', '( ( 1 / 2 ) e. ( 0 [,] 1 ) <-> ( ( 1 / 2 ) e. RR /\\ 0 <_ ( 1 / 2 ) /\\ ( 1 / 2 ) <_ 1 ) )')
w.qed([e, tri], 'mpbir', '( 1 / 2 ) e. ( 0 [,] 1 )'); run(w)

# ---- midhalf
w = W('midhalf', 'The midpoint of two complex numbers as a convex combination.')
A0 = '( M e. CC /\\ N e. CC )'
mc = w.s([], 'simpl', '( %s -> M e. CC )' % A0)
nc = w.s([], 'simpr', '( %s -> N e. CC )' % A0)
t2 = closed(w, A0, '2cn', '2 e. CC')
t2n = closed(w, A0, '2ne0', '2 =/= 0')
nm = w.s([nc, mc], 'subcld', '( %s -> ( N - M ) e. CC )' % A0)
d1 = w.s([w.s([nm, t2, t2n, w.inst('divrec2')], 'syl3anc', '( %s -> ( ( N - M ) / 2 ) = ( ( 1 / 2 ) x. ( N - M ) ) )' % A0)], 'eqcomd',
         '( %s -> ( ( 1 / 2 ) x. ( N - M ) ) = ( ( N - M ) / 2 ) )' % A0)
G = '( M + ( ( N - M ) / 2 ) )'
lhs = w.s([d1], 'oveq2d', '( %s -> ( M + ( ( 1 / 2 ) x. ( N - M ) ) ) = %s )' % (A0, G))
hq = w.s([nm, t2, t2n], 'divcld', '( %s -> ( ( N - M ) / 2 ) e. CC )' % A0)
gc = w.s([mc, hq], 'addcld', '( %s -> %s e. CC )' % (A0, G))
e1 = w.s([t2, mc, hq], 'adddid', '( %s -> ( 2 x. %s ) = ( ( 2 x. M ) + ( 2 x. ( ( N - M ) / 2 ) ) ) )' % (A0, G))
e2 = w.s([nm, t2, t2n], 'divcan2d', '( %s -> ( 2 x. ( ( N - M ) / 2 ) ) = ( N - M ) )' % A0)
e3 = w.s([mc], '2timesd', '( %s -> ( 2 x. M ) = ( M + M ) )' % A0)
e4 = w.s([e3, e2], 'oveq12d', '( %s -> ( ( 2 x. M ) + ( 2 x. ( ( N - M ) / 2 ) ) ) = ( ( M + M ) + ( N - M ) ) )' % A0)
e5 = w.s([mc, mc, nm], 'addassd', '( %s -> ( ( M + M ) + ( N - M ) ) = ( M + ( M + ( N - M ) ) ) )' % A0)
e6 = w.s([w.s([mc, nc, w.inst('pncan3')], 'syl2anc', '( %s -> ( M + ( N - M ) ) = N )' % A0)], 'oveq2d',
         '( %s -> ( M + ( M + ( N - M ) ) ) = ( M + N ) )' % A0)
ch = w.s([w.s([w.s([e1, e4], 'eqtrd', '( %s -> ( 2 x. %s ) = ( ( M + M ) + ( N - M ) ) )' % (A0, G)), e5], 'eqtrd', '( %s -> ( 2 x. %s ) = ( M + ( M + ( N - M ) ) ) )' % (A0, G)), e6], 'eqtrd',
         '( %s -> ( 2 x. %s ) = ( M + N ) )' % (A0, G))
mn = w.s([mc, nc], 'addcld', '( %s -> ( M + N ) e. CC )' % A0)
t2p = w.s([t2, t2n], 'jca', '( %s -> ( 2 e. CC /\\ 2 =/= 0 ) )' % A0)
dm = w.s([mn, gc, t2p, w.inst('divmul')], 'syl3anc', '( %s -> ( ( ( M + N ) / 2 ) = %s <-> ( 2 x. %s ) = ( M + N ) ) )' % (A0, G, G))
rr = w.s([dm, ch], 'mpbird', '( %s -> ( ( M + N ) / 2 ) = %s )' % (A0, G))
w.qed([lhs, rr], 'eqtr4d', '( %s -> ( M + ( ( 1 / 2 ) x. ( N - M ) ) ) = ( ( M + N ) / 2 ) )' % A0); run(w)

# ---- rectintqtr
w = W('rectintqtr', 'A rectangle boundary integral is the sum of the boundary integrals of its four quarters.')
XD = 'X = ( ( %s + %s ) / 2 )' % (RA, RB)
YD = 'Y = ( ( %s + %s ) / 2 )' % (IA, IB)
A0 = '( %s /\\ %s /\\ %s )' % (PS, XD, YD)
N1 = PT(RB, 'Y'); N0 = PT(RA, 'Y'); XY = PT('X', 'Y')
Q2a = PT('X', IA); Q4b = PT('X', IB)
d = ctx(w, A0)
ps = w.s([], 'simp1', '( %s -> %s )' % (A0, PS))
xd = w.s([], 'simp2', '( %s -> %s )' % (A0, XD))
yd = w.s([], 'simp3', '( %s -> %s )' % (A0, YD))
ic = closed(w, A0, 'ax-icn', '_i e. CC')
arc = w.s([d['ar']], 'recnd', '( %s -> %s e. CC )' % (A0, RA))
brc = w.s([d['br']], 'recnd', '( %s -> %s e. CC )' % (A0, RB))
aic = w.s([d['ai']], 'recnd', '( %s -> %s e. CC )' % (A0, IA))
bic = w.s([d['bi']], 'recnd', '( %s -> %s e. CC )' % (A0, IB))
hu = closed(w, A0, 'halfunit', '( 1 / 2 ) e. ( 0 [,] 1 )')
mhx = w.s([arc, brc, w.inst('midhalf')], 'syl2anc', '( %s -> ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) = ( ( %s + %s ) / 2 ) )' % (A0, RA, RB, RA, RA, RB))
mhy = w.s([aic, bic, w.inst('midhalf')], 'syl2anc', '( %s -> ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) = ( ( %s + %s ) / 2 ) )' % (A0, IA, IB, IA, IA, IB))
xd2 = w.s([xd, mhx], 'eqtr4d', '( %s -> X = ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) )' % (A0, RA, RB, RA))
yd2 = w.s([yd, mhy], 'eqtr4d', '( %s -> Y = ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) )' % (A0, IA, IB, IA))
trx = w.s([d['ar'], d['br'], d['ler']], '3jca', '( %s -> ( %s e. RR /\\ %s e. RR /\\ %s <_ %s ) )' % (A0, RA, RB, RA, RB))
tri = w.s([d['ai'], d['bi'], d['lei']], '3jca', '( %s -> ( %s e. RR /\\ %s e. RR /\\ %s <_ %s ) )' % (A0, IA, IB, IA, IB))
xI = w.s([xd2, w.s([trx, hu, w.inst('crectlin')], 'syl2anc', '( %s -> ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) e. %s )' % (A0, RA, RB, RA, RI('A', 'B')))], 'eqeltrd', '( %s -> X e. %s )' % (A0, RI('A', 'B')))
yI = w.s([yd2, w.s([tri, hu, w.inst('crectlin')], 'syl2anc', '( %s -> ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) e. %s )' % (A0, IA, IB, IA, II('A', 'B')))], 'eqeltrd', '( %s -> Y e. %s )' % (A0, II('A', 'B')))
exI = w.s([d['ar'], d['br'], w.inst('elicc2')], 'syl2anc', '( %s -> ( X e. %s <-> ( X e. RR /\\ %s <_ X /\\ X <_ %s ) ) )' % (A0, RI('A', 'B'), RA, RB))
tX = w.s([exI, xI], 'mpbid', '( %s -> ( X e. RR /\\ %s <_ X /\\ X <_ %s ) )' % (A0, RA, RB))
xr = w.s([tX, w.inst('simp1')], 'syl', '( %s -> X e. RR )' % A0)
axX = w.s([tX, w.inst('simp2')], 'syl', '( %s -> %s <_ X )' % (A0, RA))
xXb = w.s([tX, w.inst('simp3')], 'syl', '( %s -> X <_ %s )' % (A0, RB))
eyI = w.s([d['ai'], d['bi'], w.inst('elicc2')], 'syl2anc', '( %s -> ( Y e. %s <-> ( Y e. RR /\\ %s <_ Y /\\ Y <_ %s ) ) )' % (A0, II('A', 'B'), IA, IB))
tY = w.s([eyI, yI], 'mpbid', '( %s -> ( Y e. RR /\\ %s <_ Y /\\ Y <_ %s ) )' % (A0, IA, IB))
yr = w.s([tY, w.inst('simp1')], 'syl', '( %s -> Y e. RR )' % A0)
ayY = w.s([tY, w.inst('simp2')], 'syl', '( %s -> %s <_ Y )' % (A0, IA))
yYb = w.s([tY, w.inst('simp3')], 'syl', '( %s -> Y <_ %s )' % (A0, IB))
xc = w.s([xr], 'recnd', '( %s -> X e. CC )' % A0)
yc = w.s([yr], 'recnd', '( %s -> Y e. CC )' % A0)
iy = w.s([ic, yc], 'mulcld', '( %s -> ( _i x. Y ) e. CC )' % A0)
iia = w.s([ic, aic], 'mulcld', '( %s -> ( _i x. %s ) e. CC )' % (A0, IA))
iib = w.s([ic, bic], 'mulcld', '( %s -> ( _i x. %s ) e. CC )' % (A0, IB))
n1c = w.s([brc, iy], 'addcld', '( %s -> %s e. CC )' % (A0, N1))
n0c = w.s([arc, iy], 'addcld', '( %s -> %s e. CC )' % (A0, N0))
xyc = w.s([xc, iy], 'addcld', '( %s -> %s e. CC )' % (A0, XY))
q2c = w.s([xc, iia], 'addcld', '( %s -> %s e. CC )' % (A0, Q2a))
q4c = w.s([xc, iib], 'addcld', '( %s -> %s e. CC )' % (A0, Q4b))
# coordinates
def coord(V, W, vr, wr):
    a = w.s([vr, wr, w.inst('crre')], 'syl2anc', '( %s -> %s = %s )' % (A0, RE(PT(V, W)), V))
    b = w.s([vr, wr, w.inst('crim')], 'syl2anc', '( %s -> %s = %s )' % (A0, IM(PT(V, W)), W))
    return a, b
reN1, imN1 = coord(RB, 'Y', d['br'], yr)
reN0, imN0 = coord(RA, 'Y', d['ar'], yr)
reXY, imXY = coord('X', 'Y', xr, yr)
reQ2, imQ2 = coord('X', IA, xr, d['ai'])
reQ4, imQ4 = coord('X', IB, xr, d['bi'])
eqA = w.s([], 'eqidd', '( %s -> %s = %s )' % (A0, RA, RA))
eqAi = w.s([], 'eqidd', '( %s -> %s = %s )' % (A0, IA, IA))
eqB = w.s([], 'eqidd', '( %s -> %s = %s )' % (A0, RB, RB))
eqBi = w.s([], 'eqidd', '( %s -> %s = %s )' % (A0, IB, IB))
lear = w.s([d['ar']], 'leidd', '( %s -> %s <_ %s )' % (A0, RA, RA))
lebr = w.s([d['br']], 'leidd', '( %s -> %s <_ %s )' % (A0, RB, RB))
leai = w.s([d['ai']], 'leidd', '( %s -> %s <_ %s )' % (A0, IA, IA))
lebi = w.s([d['bi']], 'leidd', '( %s -> %s <_ %s )' % (A0, IB, IB))
# --- the horizontal cut
vsp = w.s([ps, hu, yd2, w.inst('rectintvsp')], 'syl3anc',
          '( %s -> ( F rectint <. A , B >. ) = ( ( F rectint <. A , %s >. ) + ( F rectint <. %s , B >. ) ) )' % (A0, N1, N0))
# --- PS for the bottom half < A , N1 >
ps1 = psub(w, A0, d, 'A', N1, d['ac'], n1c, eqA, eqAi, reN1, imN1, d['ler'], ayY, lear, lebr, leai, yYb)
# --- PS for the top half < N0 , B >
ps2 = psub(w, A0, d, N0, 'B', n0c, d['bc'], reN0, imN0, eqB, eqBi, d['ler'], yYb, lear, lebr, ayY, lebi)
# --- the vertical cut of the bottom half
rn1c = w.s([reN1], 'eqcomd', '( %s -> %s = %s )' % (A0, RB, RE(N1)))
h1a = w.s([rn1c], 'oveq1d', '( %s -> ( %s - %s ) = ( %s - %s ) )' % (A0, RB, RA, RE(N1), RA))
h1b = w.s([h1a], 'oveq2d', '( %s -> ( ( 1 / 2 ) x. ( %s - %s ) ) = ( ( 1 / 2 ) x. ( %s - %s ) ) )' % (A0, RB, RA, RE(N1), RA))
h1c = w.s([h1b], 'oveq2d', '( %s -> ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) = ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) )' % (A0, RA, RB, RA, RA, RE(N1), RA))
hyp1 = w.s([xd2, h1c], 'eqtrd', '( %s -> X = ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) )' % (A0, RA, RE(N1), RA))
OLD1 = PT('X', IM(N1))
hsp1 = w.s([ps1, hu, hyp1, w.inst('rectinthsp')], 'syl3anc',
           '( %s -> ( F rectint <. A , %s >. ) = ( ( F rectint <. A , %s >. ) + ( F rectint <. %s , %s >. ) ) )' % (A0, N1, OLD1, Q2a, N1))
s1 = w.s([imN1], 'oveq2d', '( %s -> ( _i x. %s ) = ( _i x. Y ) )' % (A0, IM(N1)))
s2 = w.s([s1], 'oveq2d', '( %s -> %s = %s )' % (A0, OLD1, XY))
o1 = w.s([s2], 'opeq2d', '( %s -> <. A , %s >. = <. A , %s >. )' % (A0, OLD1, XY))
o2 = w.s([o1], 'oveq2d', '( %s -> ( F rectint <. A , %s >. ) = ( F rectint <. A , %s >. ) )' % (A0, OLD1, XY))
I1 = '( F rectint <. A , %s >. )' % XY; I2 = '( F rectint <. %s , %s >. )' % (Q2a, N1)
o3 = w.s([o2], 'oveq1d', '( %s -> ( ( F rectint <. A , %s >. ) + %s ) = ( %s + %s ) )' % (A0, OLD1, I2, I1, I2))
hsp1c = w.s([hsp1, o3], 'eqtrd', '( %s -> ( F rectint <. A , %s >. ) = ( %s + %s ) )' % (A0, N1, I1, I2))
# --- the vertical cut of the top half
rn0c = w.s([reN0], 'eqcomd', '( %s -> %s = %s )' % (A0, RA, RE(N0)))
h2a = w.s([rn0c], 'oveq2d', '( %s -> ( %s - %s ) = ( %s - %s ) )' % (A0, RB, RA, RB, RE(N0)))
h2b = w.s([h2a], 'oveq2d', '( %s -> ( ( 1 / 2 ) x. ( %s - %s ) ) = ( ( 1 / 2 ) x. ( %s - %s ) ) )' % (A0, RB, RA, RB, RE(N0)))
h2c = w.s([rn0c, h2b], 'oveq12d', '( %s -> ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) = ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) )' % (A0, RA, RB, RA, RE(N0), RB, RE(N0)))
hyp2 = w.s([xd2, h2c], 'eqtrd', '( %s -> X = ( %s + ( ( 1 / 2 ) x. ( %s - %s ) ) ) )' % (A0, RE(N0), RB, RE(N0)))
OLD2 = PT('X', IM(N0))
hsp2 = w.s([ps2, hu, hyp2, w.inst('rectinthsp')], 'syl3anc',
           '( %s -> ( F rectint <. %s , B >. ) = ( ( F rectint <. %s , %s >. ) + ( F rectint <. %s , B >. ) ) )' % (A0, N0, N0, Q4b, OLD2))
t1 = w.s([imN0], 'oveq2d', '( %s -> ( _i x. %s ) = ( _i x. Y ) )' % (A0, IM(N0)))
t2 = w.s([t1], 'oveq2d', '( %s -> %s = %s )' % (A0, OLD2, XY))
t3 = w.s([t2], 'opeq1d', '( %s -> <. %s , B >. = <. %s , B >. )' % (A0, OLD2, XY))
t4 = w.s([t3], 'oveq2d', '( %s -> ( F rectint <. %s , B >. ) = ( F rectint <. %s , B >. ) )' % (A0, OLD2, XY))
I3 = '( F rectint <. %s , B >. )' % XY; I4 = '( F rectint <. %s , %s >. )' % (N0, Q4b)
t5 = w.s([t4], 'oveq2d', '( %s -> ( %s + ( F rectint <. %s , B >. ) ) = ( %s + %s ) )' % (A0, I4, OLD2, I4, I3))
hsp2c = w.s([hsp2, t5], 'eqtrd', '( %s -> ( F rectint <. %s , B >. ) = ( %s + %s ) )' % (A0, N0, I4, I3))
# --- assemble, and put the quarters in the order 1,2,3,4
comb = w.s([hsp1c, hsp2c], 'oveq12d',
           '( %s -> ( ( F rectint <. A , %s >. ) + ( F rectint <. %s , B >. ) ) = ( ( %s + %s ) + ( %s + %s ) ) )' % (A0, N1, N0, I1, I2, I4, I3))
ps3 = psub(w, A0, d, XY, 'B', xyc, d['bc'], reXY, imXY, eqB, eqBi, xXb, yYb, axX, lebr, ayY, lebi)
ps4 = psub(w, A0, d, N0, Q4b, n0c, q4c, reN0, imN0, reQ4, imQ4, axX, yYb, lear, xXb, ayY, lebi)
i3cc = w.s([ps3, w.inst('rectintcl')], 'syl', '( %s -> %s e. CC )' % (A0, I3))
i4cc = w.s([ps4, w.inst('rectintcl')], 'syl', '( %s -> %s e. CC )' % (A0, I4))
swap = w.s([i4cc, i3cc], 'addcomd', '( %s -> ( %s + %s ) = ( %s + %s ) )' % (A0, I4, I3, I3, I4))
sw2 = w.s([swap], 'oveq2d', '( %s -> ( ( %s + %s ) + ( %s + %s ) ) = ( ( %s + %s ) + ( %s + %s ) ) )' % (A0, I1, I2, I4, I3, I1, I2, I3, I4))
ch1 = w.s([vsp, comb], 'eqtrd', '( %s -> ( F rectint <. A , B >. ) = ( ( %s + %s ) + ( %s + %s ) ) )' % (A0, I1, I2, I4, I3))
w.qed([ch1, sw2], 'eqtrd', '( %s -> ( F rectint <. A , B >. ) = ( ( %s + %s ) + ( %s + %s ) ) )' % (A0, I1, I2, I3, I4))
run(w)
