# tm2clval
w = W('tm2clval', 'Value of TM2cl at a type triple T and a function H: the clause mapping on statements and (state, stacks) pairs.')
body = defbody('df-tm2cl'); inner = body.split('|->', 1)[1].rsplit(')', 1)[0].strip()
A = '( t = T /\\ h = H )'
l1 = w.s([], 'simpl', '( %s -> t = T )' % A); l2 = w.s([], 'simpr', '( %s -> h = H )' % A)
c, innerT = w.congr(inner, {'t': 'T', 'h': 'H'}, A, {'t': l1, 'h': l2})
assert innerT == CLMPO('T', 'H'), (innerT[:100], CLMPO('T','H')[:100])
d = w.s([], 'df-tm2cl', 'TM2cl = %s' % body)
f = w.s([c, d], 'ovmpoga', '( ( T e. _V /\\ H e. _V /\\ %s e. _V ) -> ( T TM2cl H ) = %s )' % (innerT, innerT))
e1 = w.s([], 'fvex', '( TM2Stmt ` T ) e. _V')
e2 = w.s([], 'fvex', '( 2nd ` T ) e. _V')
e3 = w.s([], 'fvex', '( TM2Stk ` T ) e. _V')
e4a = w.inst('xpexg'); e4 = w.s([e2, e3, e4a], 'mp2an', '%s e. _V' % PR('T'))
e5a = w.inst('mpoexga'); e5 = w.s([e1, e4, e5a], 'mp2an', '%s e. _V' % innerT)
B = '( T e. V /\\ H e. W )'
x1 = w.s([], 'elex', '( T e. V -> T e. _V )'); x2 = w.s([], 'elex', '( H e. W -> H e. _V )')
