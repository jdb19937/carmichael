def setness(w, expr, ante=None):
    """emit closed set-ness steps for a class built from if/op/ov/fv; returns step name of `expr e. _V`"""
    n = parse(expr)
    def go(n):
        if n.kind == 'if':
            a = go(n.kids[1]); b = go(n.kids[2])
            return w.s([a, b], 'ifex', '%s e. _V' % n.text())
        if n.kind == 'op': return w.s([], 'opex', '%s e. _V' % n.text())
        if n.kind == 'ov': return w.s([], 'ovex', '%s e. _V' % n.text())
        if n.kind == 'fv': return w.s([], 'fvex', '%s e. _V' % n.text())
        raise NotImplementedError(n.kind)
    return go(n)

# tm2stkval
w = W('tm2stkval', 'Value of TM2Stk: the stacks of a machine with stack alphabets G, one word over ( G ` k ) per stack index k.')
body = defbody('df-tm2stk').split('|->', 1)[1].rsplit(')', 1)[0].strip()
l1 = w.s([], 'id', '( t = T -> t = T )')
c, bodyT = w.congr(body, {'t': 'T'}, 't = T', {'t': l1})
d = w.s([], 'df-tm2stk', 'TM2Stk = %s' % defbody('df-tm2stk'))
f = w.s([c, d], 'fvmptg', '( ( T e. _V /\\ %s e. _V ) -> ( TM2Stk ` T ) = %s )' % (bodyT, bodyT))
e1 = w.s([], 'fvex', '( ( 1st ` ( 1st ` T ) ) ` k ) e. _V')
e2a = w.inst('wrdexg')
e2 = w.s([e1, e2a], 'ax-mp', 'Word ( ( 1st ` ( 1st ` T ) ) ` k ) e. _V')
e3 = w.s([e2], 'rgenw', 'A. k e. dom ( 1st ` ( 1st ` T ) ) Word ( ( 1st ` ( 1st ` T ) ) ` k ) e. _V')
e4a = w.inst('ixpexg')
e4 = w.s([e3, e4a], 'ax-mp', '%s e. _V' % bodyT)
m = w.s([e4, f], 'mpan2', '( T e. _V -> ( TM2Stk ` T ) = %s )' % bodyT)
x = w.s([], 'elex', '( T e. V -> T e. _V )')
w.qed([x, m], 'syl', '( T e. V -> ( TM2Stk ` T ) = %s )' % bodyT)
w.run()

