def lift(w, step, tail, antes):
    cur = step
    for a in antes:
        cur = w.s([cur], 'adantr', '( %s -> %s )' % (a, tail))
    return cur


def poolctx(w, H, q1, zn, kn):
    """FP0, K e. NN0 and the pool closures under H"""
    ss, fin, f0 = fpp(w, H, q1)
    kn0 = w.s([kn], 'nnnn0d', '( %s -> K e. NN0 )' % H)
    trip = w.s([f0, zn, kn0], '3jca', '( %s -> ( Q e. %s /\\ Z e. NN0 /\\ K e. NN0 ) )' % (H, FP0))
    return ss, fin, f0, kn0, trip


