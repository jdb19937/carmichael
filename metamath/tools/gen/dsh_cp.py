"""Sortie DSH: copy a Z6 generator module to tools/gen/dsh_<name>.py with the text substitution dsub
applied to its source, labels z6X -> dshX, imports of z6*lib -> dshenv, of z6b_*/z6c_* -> the copies.
Run: python3 tools/gen/dsh_cp.py z6b_s z6b_r ..."""
import sys, os, re
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from dshlib import dsub, LABMAP, Y151

G = os.path.dirname(os.path.abspath(__file__))
for m in sys.argv[1:]:
    s = open(os.path.join(G, m + '.py')).read()
    s = dsub(s).replace('( 6 / 5 )', Y151)
    for k, v in LABMAP.items():
        s = re.sub(r'\b%s\b' % k, v, s)
    s = re.sub(r'from (z6alib|z6blib|z6clib) import \*', 'from dshenv import *', s)
    s = re.sub(r'from (z6alib|z6blib|z6clib) import ', 'from dshenv import ', s)
    s = re.sub(r'\b(z6[bc]_[a-z0-9]+)\b', lambda mm: 'dsh_' + mm.group(1)[2:], s)
    out = os.path.join(G, 'dsh_' + m[2:] + '.py')
    open(out, 'w').write('# GENERATED by tools/gen/dsh_cp.py from %s.py (text substitution dsub); edit the copy freely\n' % m + s)
    print(out)
